import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {readFile,mkdir} from 'node:fs/promises';
import {encodeWav} from '../dist/audio/wav.js';
await mkdir('test-results',{recursive:true});
const browser=await chromium.launch({headless:true,channel:process.env.BROWSER_CHANNEL??'msedge'});
try{
 const page=await browser.newPage({viewport:{width:1440,height:1000},acceptDownloads:true}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));await page.goto('http://127.0.0.1:4173');await page.locator('.hit').first().waitFor();
 const data=Float32Array.from({length:44100},(_,i)=>Math.sin(i/44100*440*2*Math.PI)*.3);
 const wav=Buffer.from(encodeWav([data,data],44100));
 await page.setInputFiles('#sample-file',{name:'test-break.wav',mimeType:'audio/wav',buffer:wav});
 await page.waitForFunction(()=>document.querySelector('#sample-meta').textContent.includes('test-break.wav'));
 assert.match(await page.locator('#sample-meta').textContent(),/Stereo/);
 await page.click('#sample-loop');await page.click('#sample-play');assert.equal(await page.locator('#sample-play').textContent(),'Pause sample');
 await page.click('#sample-play');assert.equal(await page.locator('#sample-play').textContent(),'Play sample');
 await page.locator('#sample-seek').evaluate(el=>{el.value='.5';el.dispatchEvent(new Event('input'));});
 assert.match(await page.locator('#sample-time').textContent(),/0.50/);
 await page.click('#sample-stop');assert.match(await page.locator('#sample-time').textContent(),/0.00/);
 const download=async(id)=>{const pending=page.waitForEvent('download');await page.click(id);return readFile(await (await pending).path());};
 await page.selectOption('#chop-mode','grid');await page.selectOption('#chop-count','4');await page.click('#autochop');
 assert.equal(await page.locator('#slice-list button').count(),4);
 await page.locator('#slice-list button').nth(1).click();await page.fill('#marker-time','0.3');await page.click('#marker-apply');
 assert.equal(Number(await page.inputValue('#marker-time')),0.3);
 await page.click('#slice-play');assert.match(await page.locator('#sample-status').textContent(),/Auditioning slice 2/);
 await page.click('#sample-stop');await page.click('#marker-delete');assert.equal(await page.locator('#slice-list button').count(),3);
 await page.click('#chop-undo');assert.equal(await page.locator('#slice-list button').count(),4);
 await page.click('#chop-redo');assert.equal(await page.locator('#slice-list button').count(),3);
 const box=await page.locator('#waveform').boundingBox();
 await page.mouse.dblclick(box.x+box.width*.4,box.y+70);assert.equal(await page.locator('#slice-list button').count(),4);
 await page.mouse.move(box.x+box.width*.4,box.y+60);await page.mouse.down();await page.mouse.move(box.x+box.width*.45,box.y+60);await page.mouse.up();
 assert.ok(Math.abs(Number(await page.inputValue('#marker-time'))-.45)<.01);
 await page.click('#chop-undo');assert.ok(Math.abs(Number(await page.inputValue('#marker-time'))-.4)<.01);
 const sample=await download('#sample-export');assert.equal(sample.toString('ascii',0,4),'RIFF');assert.equal(sample.readUInt16LE(22),2);
 const pattern=await download('#export-wav');assert.equal(pattern.toString('ascii',8,12),'WAVE');assert.ok(pattern.length>sample.length);
 await page.setInputFiles('#sample-file',{name:'bad.wav',mimeType:'audio/wav',buffer:Buffer.from('bad')});
 await page.waitForFunction(()=>document.querySelector('#sample-status').textContent.includes('previous sample'));
 assert.match(await page.locator('#sample-meta').textContent(),/test-break.wav/);
 await page.click('#sample-play');await page.click('#play');assert.equal(await page.locator('#sample-play').textContent(),'Play sample');await page.click('#play');
 await page.screenshot({path:'test-results/sample-import.png',fullPage:true});
 await page.setViewportSize({width:390,height:900});assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 await page.click('#sample-remove');assert.equal(await page.locator('#sample-play').isDisabled(),true);assert.equal(await page.locator('#sample-meta').textContent(),'No sample loaded');
 assert.equal(await page.locator('body').innerText().then(s=>s.includes('Renoise')),false);assert.deepEqual(errors,[]);
 console.log('Sample browser: WAV import, stereo waveform, transport, seeking, invalid-file recovery, both WAV exports, exclusive playback and mobile layout passed.');
}finally{await browser.close();}
