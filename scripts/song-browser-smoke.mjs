import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {readFile,mkdir} from 'node:fs/promises';
import {newBank} from '../dist/core/bank.js';
import {generate} from '../dist/core/generate.js';
import {defaults} from '../dist/core/profiles.js';
import {makeProject} from '../dist/audio/project.js';
import {defaultKitState,withDrumKit} from '../dist/audio/drum-kit.js';
import {arrange} from '../dist/core/bank.js';
import {renderSequence} from '../dist/audio/performance.js';
import {encodeWav} from '../dist/audio/wav.js';
const bank=newBank(generate({...defaults(),bpm:180,bars:1}));
bank.songBpm=240;
bank.slots[1].editor=structuredClone(bank.slots[0].editor);
bank.slots[1].editor.pattern=generate({...defaults(),bpm:100,bars:2,resolution:32,seed:'song-test'});
bank.slots[0].editor.lockedRoles=['kick'];
bank.sequence=[{slot:0,repeats:2,section:'Intro'},{slot:1,repeats:1,section:'Drop'}];
const kit=defaultKitState();
const project=makeProject(bank.slots[0].editor,bank.slots[0].editor.pattern.settings,kit,new Map(),bank);
const browser=await chromium.launch({headless:true,channel:process.env.BROWSER_CHANNEL??'msedge'});
try {
 const page=await browser.newPage({viewport:{width:1440,height:1000},acceptDownloads:true});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(process.env.APP_URL??'http://127.0.0.1:4173');
 await page.waitForFunction(()=>document.querySelector('#save-status').textContent==='Saved locally');
 await page.setInputFiles('#project-open',{name:'song.bbproject',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(project))});
 await page.waitForFunction(()=>document.querySelector('#status').textContent.includes('Project opened'));
 await page.click('#show-arrangement');
 assert.equal(await page.locator('.timeline-block').count(),2);
 assert.match(await page.locator('[data-timeline-step="0"]').textContent(),/Intro/);
 assert.match(await page.locator('[data-timeline-step="1"]').textContent(),/Drop/);
 assert.equal(await page.inputValue('#song-bpm'),'240');
 await page.click('#slot-1');assert.equal(await page.inputValue('#song-bpm'),'240');
 await page.selectOption('#transport-target','song');
 assert.equal(await page.locator('#hud-bpm-val').textContent(),'240.0');
 await page.click('#play');
 await page.waitForFunction(()=>document.querySelector('[data-step="0"]').classList.contains('playing-step'));
 assert.equal(await page.locator('#song-timeline [data-timeline-step="0"]').evaluate(e=>e.classList.contains('playing-step')),true);
 assert.equal(await page.locator('#slot-0').getAttribute('aria-pressed'),'true');
 await page.waitForFunction(()=>document.querySelector('#song-position').textContent.includes('Repeat 2 / 2'));
 await page.waitForFunction(()=>document.querySelector('[data-step="1"]').classList.contains('playing-step'));
 assert.equal(await page.locator('#song-timeline [data-timeline-step="1"]').evaluate(e=>e.classList.contains('playing-step')),true);
 assert.equal(await page.locator('#slot-1').getAttribute('aria-pressed'),'true');
 assert.equal(await page.locator('.playing-row').count(),1);
 await page.waitForFunction(()=>document.querySelector('#transport-state').textContent==='Stopped');
 assert.equal(await page.locator('.playing-row,.playing-step').count(),0);
 const dl=async id=>{const pending=page.waitForEvent('download');await page.click(id);return readFile(await(await pending).path());};
 await page.selectOption('#export-target','song');assert.equal(await page.locator('#export-mode').isDisabled(),true);
 const wav=await dl('#export-wav');
 const rendered=renderSequence(arrange(bank).map(p=>withDrumKit(p,new Map(),kit)),new Map(),44100,Object.fromEntries(Object.entries(kit).map(([role,s])=>[role,s.effects])));
 assert.deepEqual(wav,Buffer.from(encodeWav(rendered.channels,rendered.sampleRate)));
 await page.selectOption('#export-target','pattern');assert.equal(await page.locator('#export-mode').isDisabled(),false);
 const patternWav=await dl('#export-wav');assert.notDeepEqual(wav,patternWav);
 await page.locator('#song-timeline').evaluate(e=>e.scrollLeft=0);
 await page.locator('[data-timeline-step="1"]').dragTo(page.locator('.timeline-insert').first());
 assert.match(await page.locator('[data-step="0"] > span').textContent(),/B/);
 assert.match(await page.locator('[data-timeline-step="0"]').textContent(),/Drop/);
 await page.click('#arr-undo');assert.match(await page.locator('[data-timeline-step="0"]').textContent(),/Intro/);
 await page.click('#arr-redo');assert.match(await page.locator('[data-timeline-step="0"]').textContent(),/Drop/);
 await page.locator('[data-timeline-step="1"]').click();
 assert.equal(await page.locator('#slot-0').getAttribute('aria-pressed'),'true');
 await page.locator('[data-step="0"] button').filter({hasText:'Move down'}).click();
 assert.match(await page.locator('[data-step="0"] > span').textContent(),/A/);
 await page.selectOption('#append-slot','1');
 await page.locator('.timeline-insert').first().click();
 assert.equal(await page.locator('.timeline-block').count(),3);
 await page.locator('[aria-label="Section name for step 1"]').fill('Build');
 await page.locator('[aria-label="Section name for step 1"]').press('Tab');
 assert.match(await page.locator('[data-timeline-step="0"]').textContent(),/Build/);
 await page.fill('#song-bpm','150');await page.locator('#song-bpm').press('Tab');
 const saved=JSON.parse(await dl('#project-save'));
 assert.equal(saved.version,2);assert.equal(saved.bank.songBpm,150);
 assert.deepEqual(saved.bank.sequence.map(step=>step.section),['Build','Intro','Drop']);
 assert.equal(saved.bank.slots[0].editor.pattern.settings.bpm,180);
 assert.equal(saved.bank.slots[1].editor.pattern.settings.bpm,100);
 assert.deepEqual(saved.bank.slots[0].editor.lockedRoles,['kick']);
 await page.waitForFunction(()=>document.querySelector('#save-status').textContent==='Saved locally');
 await page.reload();await page.waitForFunction(()=>document.querySelector('#save-status').textContent==='Restored local workspace');
 assert.equal(await page.inputValue('#song-bpm'),'150');
 await page.click('#show-arrangement');
 assert.equal(await page.locator('.timeline-block').count(),3);
 assert.match(await page.locator('[data-timeline-step="0"]').textContent(),/Build/);
 await page.selectOption('#transport-target','song');await page.click('#play');
 await page.selectOption('#transport-target','pattern');
 assert.equal(await page.locator('#transport-state').textContent(),'Stopped');
 for(const width of [1440,390]){
  await page.setViewportSize({width,height:1000});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 }
 await mkdir('test-results',{recursive:true});
 await page.screenshot({path:'test-results/song-mobile.png',fullPage:true});
 await page.setViewportSize({width:1440,height:1000});
 await page.screenshot({path:'test-results/song-desktop.png',fullPage:true});
 assert.deepEqual(errors,[]);
 console.log('Song browser: transport, tracker follow, repeats, exact WAV render, targets, drag/buttons, tempo persistence, locks and responsive layout passed.');
}finally{await browser.close();}
